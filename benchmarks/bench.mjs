#!/usr/bin/env node
/**
 * Reproducible benchmark harness for variant.
 *
 * Measures five things against deterministic generated fixture projects:
 *   1. CLI startup — `variant --help`
 *   2. Warm run    — cache hit at 100 / 1,000 / 10,000 files (hashing scale)
 *   3. Cold run    — no cache, 1,000-file project
 *   4. Overhead    — cold run minus a raw baseline of the wrapped command,
 *                    i.e. variant's own orchestration cost
 *   5. Semantic    — `variant impact` over a git fixture with N changed files;
 *                    this is the differ + git-read path, which scales with the
 *                    size of the diff rather than the size of the project
 *
 * Uses hyperfine (https://github.com/sharkdp/hyperfine) when it is on PATH,
 * otherwise falls back to a built-in timer with the same warmup/run protocol.
 *
 * Usage:
 *   pnpm build && pnpm bench                          # full run
 *   node benchmarks/bench.mjs --quick                 # fewer runs, no 10k tier
 *   node benchmarks/bench.mjs --assert-startup-ms 200 # CI regression gate
 *
 * Progress goes to stderr; the final markdown report goes to stdout, so
 * `node benchmarks/bench.mjs | tee -a "$GITHUB_STEP_SUMMARY"` works. Results
 * are also written to benchmarks/results/latest.{md,json}.
 */
import { spawnSync } from "node:child_process";
import {
	existsSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { arch, cpus, platform, release, tmpdir, totalmem } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cliPath = join(repoRoot, "dist", "cli.js");
const resultsDir = join(repoRoot, "benchmarks", "results");
const nodeBin = process.execPath;

function logProgress(message) {
	console.error(message);
}

function fail(message) {
	console.error(`bench: ${message}`);
	process.exit(1);
}

function parseArgs(argv) {
	const options = { quick: false, assertStartupMs: undefined };
	for (let i = 0; i < argv.length; i++) {
		const argument = argv[i];
		if (argument === "--quick") {
			options.quick = true;
		} else if (argument === "--assert-startup-ms") {
			i += 1;
			const value = Number(argv[i]);
			if (!Number.isFinite(value) || value <= 0) {
				fail(`--assert-startup-ms expects a positive number, got "${argv[i]}"`);
			}
			options.assertStartupMs = value;
		} else {
			fail(
				`unknown option "${argument}" — supported: --quick, --assert-startup-ms <n>`,
			);
		}
	}
	return options;
}

// ---------------------------------------------------------------------------
// Fixture generation — deterministic, so runs are comparable across machines.
// ---------------------------------------------------------------------------

/** Linear congruential generator: same seed → identical fixture bytes anywhere. */
function* seededInts(seed) {
	let state = seed >>> 0;
	while (true) {
		state = (state * 1664525 + 1013904223) >>> 0;
		yield state;
	}
}

function moduleSource(index, randomInts) {
	const lines = [
		`// Deterministic fixture module #${index} — generated by benchmarks/bench.mjs`,
		`export const id${index} = ${index};`,
	];
	for (let line = 0; line < 20; line++) {
		lines.push(
			`export const value${index}x${line} = ${randomInts.next().value};`,
		);
	}
	lines.push(`export function compute${index}(input: number): number {`);
	lines.push(
		`\treturn input * ${index + 1} + ${randomInts.next().value % 1000};`,
	);
	lines.push("}");
	return `${lines.join("\n")}\n`;
}

// The executor splits commands on spaces (no shell quoting), so the task
// command must stay quote-free. `node --version` is cheap and universal,
// which keeps the cold run dominated by variant's own work — exactly what
// the overhead measurement needs.
const fixtureConfig = `export default {
	strategy: "adaptive",
	git: { enabled: false },
	tasks: {
		build: {
			command: "node --version",
			inputs: ["package.json", "src/**/*.ts"],
		},
	},
};
`;

function generateFixture(fileCount) {
	const dir = mkdtempSync(join(tmpdir(), `variant-bench-${fileCount}-`));
	writeFileSync(
		join(dir, "package.json"),
		`${JSON.stringify(
			{
				name: `variant-bench-fixture-${fileCount}`,
				private: true,
				version: "0.0.0",
			},
			null,
			2,
		)}\n`,
	);
	writeFileSync(join(dir, "variant.config.ts"), fixtureConfig);
	const sourceDir = join(dir, "src");
	mkdirSync(sourceDir);
	const randomInts = seededInts(fileCount);
	for (let index = 0; index < fileCount; index++) {
		writeFileSync(
			join(sourceDir, `module-${index}.ts`),
			moduleSource(index, randomInts),
		);
	}
	return dir;
}

// ---------------------------------------------------------------------------
// Semantic fixture — a real git repo, because `variant impact` reads both sides
// of every changed file out of git and classifies them with the AST differ.
// The cost scales with the diff, so the fixture commits everything and then
// dirties a fixed slice of the working tree.
// ---------------------------------------------------------------------------

function semanticModuleSource(index, signatureVariant) {
	const previous =
		index > 0
			? `import { compute${index - 1} } from "./module-${index - 1}.js";\n`
			: "";
	const upstream = index > 0 ? ` + compute${index - 1}(input)` : "";
	// The changed variant alters the exported parameter list, so the differ
	// classifies it `breaking` and the blast radius actually propagates —
	// the expensive path, which is the one worth measuring.
	const signature =
		signatureVariant === 0
			? `export function compute${index}(input: number): number {`
			: `export function compute${index}(input: number, scale: number): number {`;
	const body =
		signatureVariant === 0
			? `\treturn input * ${index + 1}${upstream};`
			: `\treturn input * scale * ${index + 1}${upstream};`;
	return [
		previous,
		`export interface Options${index} { id: number; label: string; }`,
		`export const id${index} = ${index};`,
		signature,
		body,
		"}",
		"",
	].join("\n");
}

function semanticTestSource(index) {
	return [
		`import { compute${index} } from "../module-${index}.js";`,
		"",
		`export function checks${index}(): boolean {`,
		`\treturn compute${index}(1) !== undefined;`,
		"}",
		"",
	].join("\n");
}

/**
 * Returns the fixture directory, or undefined when git is unavailable — the
 * semantic scenario is skipped rather than failing the whole run.
 */
function generateSemanticFixture(moduleCount, changedCount) {
	const dir = mkdtempSync(
		join(tmpdir(), `variant-bench-semantic-${moduleCount}-`),
	);
	writeFileSync(
		join(dir, "package.json"),
		`${JSON.stringify(
			{ name: "variant-bench-semantic", private: true, version: "0.0.0" },
			null,
			2,
		)}\n`,
	);
	const sourceDir = join(dir, "src");
	const testDir = join(sourceDir, "__tests__");
	mkdirSync(testDir, { recursive: true });
	for (let index = 0; index < moduleCount; index++) {
		writeFileSync(
			join(sourceDir, `module-${index}.ts`),
			semanticModuleSource(index, 0),
		);
		if (index % 5 === 0) {
			writeFileSync(
				join(testDir, `module-${index}.test.ts`),
				semanticTestSource(index),
			);
		}
	}

	// `-c` overrides rather than repo config so the fixture never depends on
	// the machine's global git identity; --no-verify skips any global hooks.
	const gitArgs = [
		"-c",
		"user.email=bench@example.com",
		"-c",
		"user.name=bench",
		"-c",
		"commit.gpgsign=false",
	];
	const git = (args) => spawnSync("git", [...gitArgs, ...args], { cwd: dir });
	const init = git(["init", "-q", "-b", "main"]);
	if (init.error || init.status !== 0) {
		rmSync(dir, { recursive: true, force: true });
		return undefined;
	}
	git(["add", "-A"]);
	const commit = git(["commit", "-q", "--no-verify", "-m", "fixture"]);
	if (commit.error || commit.status !== 0) {
		rmSync(dir, { recursive: true, force: true });
		return undefined;
	}

	// Dirty the working tree and leave it dirty: `--base HEAD` then sees the
	// same changed set on every timed run, with no --prepare step.
	for (let index = 0; index < changedCount && index < moduleCount; index++) {
		writeFileSync(
			join(sourceDir, `module-${index}.ts`),
			semanticModuleSource(index, 1),
		);
	}
	return dir;
}

// ---------------------------------------------------------------------------
// Measurement — hyperfine when available, built-in fallback otherwise.
// ---------------------------------------------------------------------------

function runOrThrow(argv, cwd) {
	const result = spawnSync(argv[0], argv.slice(1), {
		cwd,
		stdio: ["ignore", "pipe", "pipe"],
		encoding: "utf8",
	});
	if (result.error) throw result.error;
	if (result.status !== 0) {
		throw new Error(
			`command failed (exit ${result.status}): ${argv.join(" ")}\n${result.stdout}${result.stderr}`,
		);
	}
	return result;
}

function detectHyperfine() {
	const result = spawnSync("hyperfine", ["--version"], { encoding: "utf8" });
	if (!result.error && result.status === 0) return result.stdout.trim();
	return undefined;
}

/**
 * Quote one argv element for hyperfine's shell (`sh -c` on POSIX, `cmd /c` on
 * Windows). Double quotes work in both; arguments containing a double quote
 * cannot be quoted portably, so refuse them.
 */
function shellQuote(argument) {
	if (argument.includes('"')) {
		throw new Error(`cannot safely shell-quote: ${argument}`);
	}
	return /^[A-Za-z0-9_\-./\\:=]+$/.test(argument) ? argument : `"${argument}"`;
}

function measureWithHyperfine(scenario) {
	const exportPath = join(resultsDir, `hyperfine-${scenario.name}.json`);
	const args = [
		"--style",
		"basic",
		"--warmup",
		String(scenario.warmup),
		"--runs",
		String(scenario.runs),
		"--export-json",
		exportPath,
		"--command-name",
		scenario.name,
	];
	if (scenario.prepareArgv) {
		args.push("--prepare", scenario.prepareArgv.map(shellQuote).join(" "));
	}
	args.push(scenario.argv.map(shellQuote).join(" "));
	// Route hyperfine's stdout to our stderr so stdout stays report-only.
	const result = spawnSync("hyperfine", args, {
		cwd: scenario.cwd,
		stdio: ["ignore", 2, 2],
	});
	if (result.status !== 0) {
		throw new Error(`hyperfine failed for scenario "${scenario.name}"`);
	}
	const exported = JSON.parse(readFileSync(exportPath, "utf8"));
	rmSync(exportPath, { force: true });
	const entry = exported.results[0];
	return {
		medianMs: entry.median * 1000,
		meanMs: entry.mean * 1000,
		stddevMs: (entry.stddev ?? 0) * 1000,
		minMs: entry.min * 1000,
		timesMs: entry.times.map((seconds) => seconds * 1000),
	};
}

function mean(values) {
	return values.reduce((sum, value) => sum + value, 0) / values.length;
}

function median(values) {
	const sorted = [...values].sort((a, b) => a - b);
	const middle = Math.floor(sorted.length / 2);
	return sorted.length % 2 === 1
		? sorted[middle]
		: (sorted[middle - 1] + sorted[middle]) / 2;
}

function stddev(values) {
	if (values.length < 2) return 0;
	const average = mean(values);
	const variance =
		values.reduce((sum, value) => sum + (value - average) ** 2, 0) /
		(values.length - 1);
	return Math.sqrt(variance);
}

function measureWithFallback(scenario) {
	const runOnce = () => {
		if (scenario.prepareArgv) runOrThrow(scenario.prepareArgv, scenario.cwd);
		const start = performance.now();
		const result = spawnSync(scenario.argv[0], scenario.argv.slice(1), {
			cwd: scenario.cwd,
			stdio: "ignore",
		});
		const elapsed = performance.now() - start;
		if (result.error) throw result.error;
		if (result.status !== 0) {
			// Re-run with output captured so the failure is actionable.
			runOrThrow(scenario.argv, scenario.cwd);
			throw new Error(
				`command failed intermittently: ${scenario.argv.join(" ")}`,
			);
		}
		return elapsed;
	};
	for (let i = 0; i < scenario.warmup; i++) runOnce();
	const timesMs = [];
	for (let i = 0; i < scenario.runs; i++) timesMs.push(runOnce());
	return {
		medianMs: median(timesMs),
		meanMs: mean(timesMs),
		stddevMs: stddev(timesMs),
		minMs: Math.min(...timesMs),
		timesMs,
	};
}

// ---------------------------------------------------------------------------
// Reporting
// ---------------------------------------------------------------------------

function formatMs(ms) {
	if (ms >= 10_000) return `${(ms / 1000).toFixed(1)} s`;
	if (ms >= 1000) return `${(ms / 1000).toFixed(2)} s`;
	if (ms >= 100) return `${ms.toFixed(0)} ms`;
	return `${ms.toFixed(1)} ms`;
}

function formatCount(count) {
	return count.toLocaleString("en-US");
}

function collectEnvironment(timingTool) {
	let commit = "unknown";
	const git = spawnSync("git", ["rev-parse", "--short", "HEAD"], {
		cwd: repoRoot,
		encoding: "utf8",
	});
	if (!git.error && git.status === 0) commit = git.stdout.trim();
	const packageJson = JSON.parse(
		readFileSync(join(repoRoot, "package.json"), "utf8"),
	);
	return {
		variantVersion: packageJson.version,
		commit,
		node: process.version,
		os: `${platform()} ${release()} (${arch()})`,
		cpu: cpus()[0]?.model?.trim() ?? "unknown CPU",
		cores: cpus().length,
		memoryGb: Math.round(totalmem() / 1024 ** 3),
		timingTool,
		generatedAt: new Date().toISOString(),
	};
}

function buildMarkdown(environment, measured, orchestrationOverheadMs) {
	const lines = [
		"### variant benchmarks",
		"",
		"| Scenario | Median | Mean ± σ | Min | Runs |",
		"|----------|-------:|---------:|----:|-----:|",
	];
	for (const scenario of measured) {
		lines.push(
			`| ${scenario.label} | ${formatMs(scenario.medianMs)} | ${formatMs(scenario.meanMs)} ± ${formatMs(scenario.stddevMs)} | ${formatMs(scenario.minMs)} | ${scenario.runs} |`,
		);
	}
	lines.push(
		`| **Orchestration overhead** — cold run − baseline (config load + DAG + hashing + cache write) | **${formatMs(orchestrationOverheadMs)}** | — | — | — |`,
	);
	lines.push(
		"",
		`Environment: ${environment.cpu} (${environment.cores} cores, ${environment.memoryGb} GB RAM), ${environment.os}, Node ${environment.node}, variant ${environment.variantVersion} @ ${environment.commit}, measured with ${environment.timingTool} on ${environment.generatedAt}.`,
		"",
		"Reproduce with `pnpm build && pnpm bench` — see `benchmarks/README.md` for methodology.",
	);
	return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
	const options = parseArgs(process.argv.slice(2));
	if (!existsSync(cliPath)) {
		fail(`${cliPath} not found — run \`pnpm build\` first`);
	}
	mkdirSync(resultsDir, { recursive: true });

	const hyperfineVersion = detectHyperfine();
	const timingTool =
		hyperfineVersion ??
		"built-in fallback timer (install hyperfine for the reference tool)";
	logProgress(`Timing tool: ${timingTool}`);

	const tiers = options.quick ? [100, 1000] : [100, 1000, 10_000];
	const primaryTier = 1000;
	const runCounts = options.quick
		? { startup: 5, warm: 5, cold: 3, semantic: 3, warmup: 1 }
		: { startup: 20, warm: 15, cold: 10, semantic: 10, warmup: 3 };
	const semanticModules = options.quick ? 100 : 300;
	const semanticChanged = options.quick ? 10 : 25;

	logProgress("Generating fixtures ...");
	const fixtures = new Map();
	for (const tier of tiers) {
		fixtures.set(tier, generateFixture(tier));
		logProgress(`  ${formatCount(tier)} files → ${fixtures.get(tier)}`);
	}
	const semanticFixture = generateSemanticFixture(
		semanticModules,
		semanticChanged,
	);
	if (semanticFixture === undefined) {
		logProgress("  semantic fixture skipped — git unavailable");
	} else {
		logProgress(
			`  ${formatCount(semanticModules)} modules, ${semanticChanged} changed → ${semanticFixture}`,
		);
	}

	try {
		// Prime every fixture's cache: first run populates, second must hit.
		for (const [tier, dir] of fixtures) {
			logProgress(`Priming cache for ${formatCount(tier)}-file fixture ...`);
			runOrThrow([nodeBin, cliPath, "build"], dir);
			runOrThrow([nodeBin, cliPath, "build"], dir);
		}

		const primaryFixture = fixtures.get(primaryTier);
		const clearCacheArgv = [
			nodeBin,
			"-e",
			"require('node:fs').rmSync('.variant',{recursive:true,force:true})",
		];

		// Warm scenarios run before the cold one so a primed cache is never
		// deleted out from under them; the cold scenario's final timed run
		// repopulates the cache it clears.
		const scenarios = [
			{
				name: "startup",
				label: "CLI startup — `variant --help`",
				argv: [nodeBin, cliPath, "--help"],
				cwd: repoRoot,
				runs: runCounts.startup,
				warmup: runCounts.warmup,
			},
			{
				name: "baseline",
				label:
					"Baseline — raw `node --version` (the command the fixture wraps)",
				argv: [nodeBin, "--version"],
				cwd: primaryFixture,
				runs: runCounts.startup,
				warmup: runCounts.warmup,
			},
			...tiers.map((tier) => ({
				name: `warm-${tier}`,
				label: `Warm run — cache hit, ${formatCount(tier)} files (build never spawned)`,
				argv: [nodeBin, cliPath, "build"],
				cwd: fixtures.get(tier),
				runs: runCounts.warm,
				warmup: runCounts.warmup,
			})),
			{
				name: "cold",
				label: `Cold run — no cache, ${formatCount(primaryTier)} files`,
				argv: [nodeBin, cliPath, "build"],
				cwd: primaryFixture,
				prepareArgv: clearCacheArgv,
				runs: runCounts.cold,
				warmup: 1,
			},
			...(semanticFixture === undefined
				? []
				: [
						{
							name: "impact",
							label: `Semantic — \`variant impact\`, ${semanticChanged} changed files of ${formatCount(semanticModules)}`,
							argv: [nodeBin, cliPath, "impact", "--base", "HEAD"],
							cwd: semanticFixture,
							runs: runCounts.semantic,
							// The first run builds the symbol graph from scratch; the
							// timed runs should measure the incremental steady state.
							warmup: Math.max(2, runCounts.warmup),
						},
					]),
		];

		const measure = hyperfineVersion
			? measureWithHyperfine
			: measureWithFallback;
		const measured = [];
		for (const scenario of scenarios) {
			logProgress(`Measuring: ${scenario.label} ...`);
			measured.push({ ...scenario, ...measure(scenario) });
		}

		const startupResult = measured.find((s) => s.name === "startup");
		const baselineResult = measured.find((s) => s.name === "baseline");
		const coldResult = measured.find((s) => s.name === "cold");
		if (!startupResult || !baselineResult || !coldResult) {
			throw new Error("expected scenario missing from results");
		}
		const orchestrationOverheadMs =
			coldResult.medianMs - baselineResult.medianMs;

		const environment = collectEnvironment(timingTool);
		const markdown = buildMarkdown(
			environment,
			measured,
			orchestrationOverheadMs,
		);
		const report = {
			environment,
			options: { quick: options.quick },
			scenarios: measured.map((scenario) => ({
				name: scenario.name,
				label: scenario.label,
				runs: scenario.runs,
				warmup: scenario.warmup,
				medianMs: scenario.medianMs,
				meanMs: scenario.meanMs,
				stddevMs: scenario.stddevMs,
				minMs: scenario.minMs,
				timesMs: scenario.timesMs,
			})),
			derived: { orchestrationOverheadMs },
		};

		writeFileSync(join(resultsDir, "latest.md"), `${markdown}\n`);
		writeFileSync(
			join(resultsDir, "latest.json"),
			`${JSON.stringify(report, null, 2)}\n`,
		);
		logProgress(
			`Results written to ${join(resultsDir, "latest.md")} and latest.json`,
		);
		console.log(markdown);

		if (options.assertStartupMs !== undefined) {
			if (startupResult.medianMs > options.assertStartupMs) {
				logProgress(
					`FAIL: startup median ${formatMs(startupResult.medianMs)} exceeds the ${options.assertStartupMs} ms gate`,
				);
				process.exitCode = 1;
			} else {
				logProgress(
					`PASS: startup median ${formatMs(startupResult.medianMs)} is within the ${options.assertStartupMs} ms gate`,
				);
			}
		}
	} finally {
		for (const dir of fixtures.values()) {
			rmSync(dir, { recursive: true, force: true });
		}
		if (semanticFixture !== undefined) {
			rmSync(semanticFixture, { recursive: true, force: true });
		}
	}
}

main();
